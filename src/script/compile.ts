/**
 * Compiles a ToonScript (JSON) into absolute-time timelines the renderer plays.
 * Pure TypeScript, no React/Remotion, so it can run in Node for checks and tests.
 */
import {CAST_PRESETS, type CharacterDesign} from '../engine/designs';
import {DEFAULT_CPS, estimateDuration, NARRATOR, type SpeechLine, wordTimings} from '../engine/speech';
import type {Keyframe} from '../engine/time';
import {
  ACCESSORIES, BACKDROPS, type BackdropName, EXPRESSIONS, type Expression, GESTURES, HAIR_STYLES, POSES, type Pose,
} from '../engine/vocab';
import type {FocusSpec, ScriptActorState, ScriptBeat, ScriptCamera, ToonScript} from './types';

export interface Issue {
  level: 'error' | 'warning';
  where: string;
  message: string;
}

export interface CompiledActor {
  id: string;
  design: CharacterDesign;
  x: Keyframe<number>[];
  y: number;
  scale: number;
  facing: Keyframe<1 | -1>[];
  pose: Keyframe<Pose>[];
  expression: Keyframe<Expression>[];
  emote: Keyframe<string | null>[];
  look: Keyframe<number>[];
}

export interface CompiledScene {
  index: number;
  start: number;
  end: number;
  backdrop: BackdropName;
  tint?: string;
  actors: CompiledActor[];
  camera: {zoom: Keyframe<number>[]; focus: Keyframe<FocusSpec>[]; y: Keyframe<number | null>[]};
}

export interface CompiledCaption {
  text: string;
  style: 'big' | 'title' | 'note';
  start: number;
  end: number;
}

export interface CompiledEpisode {
  id: string;
  title: string;
  fps: number;
  duration: number;
  accent: string;
  subtitles: 'both' | 'long' | 'short' | 'none';
  scenes: CompiledScene[];
  lines: SpeechLine[];
  captions: CompiledCaption[];
  sfx: {src: string; start: number}[];
  music?: {src: string; volume: number};
  thumbnail: {at: number; text?: string};
  speakers: Record<string, {name: string; color: string}>;
  issues: Issue[];
}

const OFFSTAGE = {left: -240, right: 2160} as const;
const WALK_SPEED = 400;
const LEAD_IN = 0.4;
const TAIL = 0.6;
const EMOTE_HOLD = 1.8;
const CAMERA_MOVE = 0.8;
/** Scripted camera moves start this early so the shot is ready when the line begins. */
const CAMERA_LEAD = 0.5;

const dir = (f: 'left' | 'right'): 1 | -1 => (f === 'left' ? -1 : 1);

/** Durations (seconds) of audio files, keyed by public/ path. Generated by `npm run sync-audio`. */
export type AudioDurations = Record<string, number>;

export function compileScript(script: ToonScript, audioDurations: AudioDurations = {}): CompiledEpisode {
  const issues: Issue[] = [];
  const err = (where: string, message: string) => issues.push({level: 'error', where, message});
  const warn = (where: string, message: string) => issues.push({level: 'warning', where, message});

  const fps = script.fps ?? 30;
  const cps = script.cps ?? DEFAULT_CPS;
  const defaultPause = script.pause ?? 0.35;

  // ---- Cast ---------------------------------------------------------------
  const cast: Record<string, CharacterDesign> = {};
  for (const [id, spec] of Object.entries(script.cast ?? {})) {
    if (id === NARRATOR) {
      err(`cast.${id}`, `"${NARRATOR}" is reserved for the off-screen voice.`);
      continue;
    }
    if (typeof spec === 'string') {
      const preset = CAST_PRESETS[spec];
      if (!preset) err(`cast.${id}`, `Unknown preset "${spec}". Available: ${Object.keys(CAST_PRESETS).join(', ')}`);
      else cast[id] = preset;
    } else {
      if (!HAIR_STYLES.includes(spec.hairStyle)) err(`cast.${id}`, `Unknown hairStyle "${spec.hairStyle}".`);
      if (spec.accessory && !ACCESSORIES.includes(spec.accessory)) err(`cast.${id}`, `Unknown accessory "${spec.accessory}".`);
      cast[id] = spec;
    }
  }
  const speakers: CompiledEpisode['speakers'] = {[NARRATOR]: {name: 'Narrator', color: '#ffffff'}};
  for (const [id, d] of Object.entries(cast)) speakers[id] = {name: d.name, color: d.color};

  const lines: SpeechLine[] = [];
  const captions: CompiledCaption[] = [];
  const sfx: CompiledEpisode['sfx'] = [];
  const scenes: CompiledScene[] = [];

  let cursor = 0;

  script.scenes.forEach((scene, si) => {
    const sw = `scenes[${si}]`;
    if (!BACKDROPS.includes(scene.backdrop)) err(sw, `Unknown backdrop "${scene.backdrop}". Available: ${BACKDROPS.join(', ')}`);
    const start = cursor;

    // ---- Actors: starting state ---------------------------------------------
    const states = scene.actors ?? {};
    const ids = Object.keys(states);
    // Unplaced actors are spread evenly across the stage.
    const defaultX = (id: string) => states[id].x ?? (1920 * (ids.indexOf(id) + 1)) / (ids.length + 1);
    const actors: Record<string, CompiledActor & {busyUntil: number; currentX: number; emoteEvents: [number, string | null, boolean][]}> = {};
    ids.forEach((id) => {
      const design = cast[id];
      if (!design) {
        err(`${sw}.actors.${id}`, `"${id}" is not in the cast.`);
        return;
      }
      const s = states[id];
      validateState(s, `${sw}.actors.${id}`, err);
      const x0 = defaultX(id);
      // An actor that "enter"s later starts off-screen.
      const firstEnter = scene.beats.flatMap((b) => b.do ?? []).find((a) => a.actor === id && a.enter);
      const startX = firstEnter?.enter ? OFFSTAGE[firstEnter.enter] : x0;
      // Default facing: towards the other actors.
      const others = ids.filter((o) => o !== id).map(defaultX);
      const avg = others.length ? others.reduce((a, b) => a + b, 0) / others.length : 960;
      const facing: 1 | -1 = s.facing ? dir(s.facing) : avg < x0 ? -1 : 1;
      actors[id] = {
        id, design,
        x: [[start, startX]],
        y: s.y ?? 0,
        scale: s.scale ?? 1,
        facing: [[start, facing]],
        pose: [[start, s.pose ?? 'idle']],
        expression: [[start, s.expression ?? 'neutral']],
        emote: [[start, null]],
        look: [[start, s.look ?? 0.4]],
        busyUntil: start, currentX: startX,
        emoteEvents: s.emote ? [[start, s.emote, true]] : [],
      };
    });
    // Spacing check.
    const xs = ids.filter((id) => actors[id]).map((id) => ({id, x: actors[id].currentX})).sort((a, b) => a.x - b.x);
    for (let i = 1; i < xs.length; i++) {
      if (xs[i].x - xs[i - 1].x < 170 && xs[i].x > 0 && xs[i].x < 1920) warn(sw, `"${xs[i - 1].id}" and "${xs[i].id}" start overlapping (${Math.round(xs[i].x - xs[i - 1].x)} apart; aim for 300+).`);
    }

    // ---- Camera ----------------------------------------------------------
    const cam = scene.camera ?? {};
    const camera: CompiledScene['camera'] = {
      zoom: [[start, cam.zoom ?? 1]],
      focus: [[start, cam.focus ?? 'auto']],
      y: [[start, cam.y ?? null]],
    };
    let currentZoom = cam.zoom ?? 1;
    let lastCameraChange = start;
    const applyCamera = (c: ScriptCamera, at: number, where: string) => {
      if (c.zoom !== undefined) {
        camera.zoom.push([at, currentZoom], [at + CAMERA_MOVE, c.zoom]);
        currentZoom = c.zoom;
      }
      if (c.focus !== undefined) {
        if (typeof c.focus === 'string' && !['auto', 'center', 'speaker'].includes(c.focus) && !actors[c.focus]) {
          err(where, `Camera focus "${c.focus}" is not an actor in this scene.`);
        }
        camera.focus.push([at, c.focus]);
      }
      if (c.y !== undefined) camera.y.push([at, c.y]);
      lastCameraChange = at;
    };

    if (scene.title) {
      captions.push({text: scene.title, style: 'title', start: start + 0.2, end: start + 2.2});
    }
    cursor = start + (scene.title ? 2.4 : LEAD_IN);

    // ---- Beats -----------------------------------------------------------
    scene.beats.forEach((beat: ScriptBeat, bi) => {
      const bw = `${sw}.beats[${bi}]`;
      const t0 = cursor;
      const who = beat.narrate !== undefined ? NARRATOR : beat.say;
      const text = beat.narrate ?? beat.text;
      let length = 0;
      let blockingUntil = t0;

      if (beat.say !== undefined && beat.narrate !== undefined) err(bw, 'Use either "say" or "narrate", not both.');
      if (who !== undefined) {
        if (!text) err(bw, 'Spoken beat has no text.');
        if (who !== NARRATOR && !cast[who]) err(bw, `Speaker "${who}" is not in the cast.`);
        if (who !== NARRATOR && cast[who] && !actors[who]) warn(bw, `"${who}" speaks but is not in this scene (off-screen voice).`);
      } else if (text) {
        err(bw, '"text" needs a "say": "<actor or narrator>".');
      }

      if (who && text) {
        let d = estimateDuration(text, cps);
        if (beat.audio) {
          const real = audioDurations[beat.audio];
          if (real === undefined) warn(bw, `No duration for "${beat.audio}" — run \`npm run sync-audio\`. Using an estimate.`);
          else d = real;
        }
        if (beat.dur !== undefined) {
          if (text.length / beat.dur > 22) warn(bw, `Line is very fast (${(text.length / beat.dur).toFixed(0)} chars/s).`);
          d = beat.dur;
        }
        if (text.length > 140) warn(bw, `Line is ${text.length} characters; split it so subtitles stay readable.`);
        lines.push({who, text, start: t0, end: t0 + d, audio: beat.audio, words: wordTimings(text, t0, t0 + d)});
        length = d;

        const speaker = actors[who];
        if (speaker) {
          if (beat.pose) setPose(speaker, beat.pose, t0, t0 + d, bw, err);
          if (beat.expression) setExpression(speaker, beat.expression, t0, bw, err);
          if (beat.emote !== undefined) speaker.emoteEvents.push([t0, beat.emote, true]);
        }
      } else if (beat.pose || beat.expression || beat.emote !== undefined) {
        warn(bw, '"pose"/"expression"/"emote" on a beat apply to its speaker; use "do" for silent beats.');
      }

      const beatEnd = () => t0 + Math.max(length, beat.dur ?? 0);

      for (const [ai, a] of (beat.do ?? []).entries()) {
        const aw = `${bw}.do[${ai}]`;
        const actor = actors[a.actor];
        if (!actor) {
          err(aw, `"${a.actor}" is not in this scene's actors.`);
          continue;
        }
        validateState(a, aw, err);
        if (a.x !== undefined && a.walkTo === undefined && !a.enter && !a.exit) {
          actor.x.push([t0, actor.currentX], [t0, a.x]);
          actor.currentX = a.x;
        }
        if (a.y !== undefined) actor.y = a.y;
        if (a.facing) actor.facing.push([t0, dir(a.facing)]);
        if (a.pose) setPose(actor, a.pose, t0, beatEnd() || t0 + 1.2, aw, err);
        if (a.expression) setExpression(actor, a.expression, t0, aw, err);
        if (a.emote !== undefined) actor.emoteEvents.push([t0, a.emote, true]);
        if (a.look !== undefined) actor.look.push([t0, a.look]);

        let target: number | undefined = a.walkTo;
        if (a.enter) target = a.walkTo ?? states[a.actor]?.x ?? 960;
        if (a.exit) target = OFFSTAGE[a.exit];
        if (target !== undefined && target !== actor.currentX) {
          const ws = Math.max(t0, actor.busyUntil);
          const d = Math.max(0.5, Math.abs(target - actor.currentX) / (a.speed ?? WALK_SPEED));
          actor.x.push([ws, actor.currentX], [ws + d, target]);
          actor.facing.push([ws, target > actor.currentX ? 1 : -1]);
          actor.busyUntil = ws + d;
          actor.currentX = target;
          blockingUntil = Math.max(blockingUntil, ws + d);
        }
      }

      if (beat.camera) applyCamera(beat.camera, Math.max(start, t0 - CAMERA_LEAD, lastCameraChange), bw);

      // Silent beats last as long as their walks (or `dur`).
      if (!who) length = beat.dur ?? Math.max(blockingUntil - t0, beat.caption ? 1.5 : 0);
      const end = t0 + length;

      if (beat.caption) {
        const c = typeof beat.caption === 'string' ? {text: beat.caption} : beat.caption;
        captions.push({text: c.text, style: c.style ?? 'big', start: t0, end: t0 + (c.hold ?? Math.max(length, 1.5))});
        lastCameraChange = t0;
      }
      if (beat.sfx) sfx.push({src: beat.sfx, start: t0});

      if (t0 - lastCameraChange > 12) {
        warn(bw, 'Over 12s without a camera move or caption — consider a zoom or cutaway to hold attention.');
        lastCameraChange = t0;
      }
      cursor = end + (beat.pause ?? (who ? defaultPause : 0));
    });

    const end = Math.max(cursor, ...Object.values(actors).map((a) => a.busyUntil)) + LEAD_IN;
    cursor = end;

    scenes.push({
      index: si, start, end, backdrop: scene.backdrop, tint: scene.tint, camera: sortTracks(camera),
      actors: Object.values(actors).map(({busyUntil, currentX, emoteEvents, ...a}) => {
        a.emote = buildEmotes(start, emoteEvents);
        return sortTracks(a);
      }),
    });
  });

  const duration = cursor + TAIL;
  if (duration > 180) warn('episode', `Episode is ${duration.toFixed(0)}s; YouTube Shorts must be 3 minutes or less.`);
  if (scenes.length === 0) err('episode', 'Script has no scenes.');

  return {
    id: script.id,
    title: script.title,
    fps,
    duration,
    accent: script.accent ?? '#ff7a3d',
    subtitles: script.subtitles ?? 'both',
    scenes, lines, captions, sfx,
    music: script.music ? {src: script.music.src, volume: script.music.volume ?? 0.15} : undefined,
    thumbnail: script.thumbnail ?? {at: Math.min(duration / 3, 6)},
    speakers,
    issues,
  };
}

function validateState(s: ScriptActorState, where: string, err: (w: string, m: string) => void) {
  if (s.pose && !POSES.includes(s.pose)) err(where, `Unknown pose "${s.pose}". Available: ${POSES.join(', ')}`);
  if (s.expression && !EXPRESSIONS.includes(s.expression)) err(where, `Unknown expression "${s.expression}". Available: ${EXPRESSIONS.join(', ')}`);
  if (s.facing && s.facing !== 'left' && s.facing !== 'right') err(where, `facing must be "left" or "right".`);
}

function setPose(a: CompiledActor, pose: Pose, at: number, until: number, where: string, err: (w: string, m: string) => void) {
  if (!POSES.includes(pose)) return err(where, `Unknown pose "${pose}". Available: ${POSES.join(', ')}`);
  a.pose.push([at, pose]);
  // Gestures (wave, point, ...) drop back to idle when the beat ends.
  if (GESTURES.includes(pose)) a.pose.push([Math.max(until, at + 0.8), 'idle']);
}

function setExpression(a: CompiledActor, e: Expression, at: number, where: string, err: (w: string, m: string) => void) {
  if (!EXPRESSIONS.includes(e)) return err(where, `Unknown expression "${e}". Available: ${EXPRESSIONS.join(', ')}`);
  a.expression.push([at, e]);
}

/** Emotes auto-hide after EMOTE_HOLD seconds unless replaced sooner. */
function buildEmotes(start: number, events: [number, string | null, boolean][]): Keyframe<string | null>[] {
  const sorted = [...events].sort((a, b) => a[0] - b[0]);
  const out: Keyframe<string | null>[] = [[start, null]];
  sorted.forEach(([t, v], i) => {
    out.push([t, v]);
    const next = sorted[i + 1]?.[0] ?? Infinity;
    if (v !== null && t + EMOTE_HOLD < next) out.push([t + EMOTE_HOLD, null]);
  });
  return out;
}

/** Stable-sort every keyframe track by time. */
function sortTracks<T extends object>(o: T): T {
  for (const v of Object.values(o)) {
    if (Array.isArray(v) && v.length && Array.isArray(v[0])) v.sort((a: Keyframe<unknown>, b: Keyframe<unknown>) => a[0] - b[0]);
  }
  return o;
}
